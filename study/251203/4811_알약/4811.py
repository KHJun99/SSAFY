# 백준_4811_알약 (G5)
"""
## [문제 정리]
- 70세 박종수 할아버지는 매일 매일 약 반알을 먹는다.
- 손녀 선영이는 종수 할아버지에게 약이 N개 담긴 병을 선물로 주었다.
- 첫째 날
    - 종수는 병에서 약을 하나 꺼낸다.
    - 약을 반으로 쪼개서 한 조각은 먹고, 다른 조각은 다시 병에 넣는다.
- 다음 날부터
    - 종수는 병에서 약을 하나 꺼낸다.(약은 한조각 or 반조각)
    - if 반조각
        - 약을 먹는다.
    - elif 한조각
        - 반을 쪼개서 한 조각을 먹고, 다른 조각은 다시 병에 넣는다.
- 종수는 손녀에게 한 조각을 꺼낸 날에는 W, 반 조각을 꺼낸 날에는 H를 보낸다.
- 총 2N일이 지나면 길이가 2N인 문자열이 만들어지게 된다.
- 이때, 가능한 서로 다른 문자열의 개수는 총 몇개인가?

"""
memo = {}
def solve(w, h):
    """
    :param w: 병에 남은 온전한 알약 개수
    :param h: 병에 남은 반 조각 개수
    :return: 이 상태에서 끝까지 가는 경우의 수
    """
    # 병이 비었으면 1가지 방법
    if w == 0 and h == 0:
        return 1

    # 이미 계산한 적 있으면 저장된 값 반환
    if (w, h) in memo:
        return memo[(w, h)]

    result = 0

    # 온전한 알약을 꺼낼 수 있으면
    if w > 0:
        result += solve(w - 1, h + 1)   # W 기록

    # 반조각을 꺼낼 수 있으면
    if h > 0:
        result += solve(w, h - 1)   # H 기록

    # 결과 메모이제이션
    memo[(w, h)] = result
    return result


while True:
    N = int(input())

    if N == 0:
        break

    # 메모 초기화 (각 테스트마다)
    memo = {}

    # 초기값 : 온전한 알약 N개, 반 조각 0개
    answer = solve(N, 0)
    print(answer)

